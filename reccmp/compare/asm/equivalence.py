@dataclass(frozen=True)
class CalleeInfo:
    pops: int | None  # bytes removed by the callee's `ret N`; None if unknown
    reads_ecx: bool = True
    reads_edx: bool = True


@dataclass(frozen=True)
class ReturnKind:
    eax: bool = True
    edx: bool = True
    st0: bool = False


class State:
    """One side's machine state at a point. Stack slots are keyed by (offset from entry esp, size)."""

    def __init__(self) -> None:
        self.regs: dict[str, int] = {}
        self.flags: int = -1
        self.fsw: int = -1
        self.mem: int = -1
        self.stack: dict[tuple[int, int], int] = {}
        # branch conditions known to hold on the way here, as (flags, cc) in canonical form
        self.facts: frozenset[tuple[int, str]] = frozenset()
        self.fpu: list[int] = []  # st(0) is the last element
        self.written: frozenset[tuple[int, int]] = (
            frozenset()
        )  # slots this function has written
        self.escaped = False
        # Arguments are pushed below this offset: where the prologue left esp after allocating
        # the frame, raised when the function removes arguments itself (add esp, pop). What is
        # written between esp and it is an argument of the next call, including what was pushed
        # before a nested call evaluated another argument.
        self.call_level = 0
        self.frame_set = False
        # the lowest stack offset a pointer that left the function's hands may reach from:
        # every call can read the frame from there up
        self.escape_floor: int | None = None
        # At most one ("clobber", floor) layer: since it was added, a call, a store through a
        # pointer or an indexed write may have changed any slot at or above `floor` that we hold
        # no value for. `layer_terms` holds the term describing those events, which includes the
        # contents the slots had before.
        self.layers: tuple[tuple[str, int], ...] = ()
        self.layer_terms: list[int] = []

    def copy(self) -> "State":
        s = State()
        s.regs = dict(self.regs)
        s.flags, s.fsw, s.mem = self.flags, self.fsw, self.mem
        s.stack = dict(self.stack)
        s.facts = self.facts
        s.fpu = list(self.fpu)
        s.written = self.written
        s.escaped = self.escaped
        s.call_level, s.frame_set = self.call_level, self.frame_set
        s.escape_floor = self.escape_floor
        s.layers = self.layers
        s.layer_terms = list(self.layer_terms)
        return s

    def locations(self) -> dict[tuple, int]:
        out: dict[tuple, int] = {
            ("r", r): t for r, t in self.regs.items() if r != "esp"
        }
        out[("flags",)] = self.flags
        out[("fsw",)] = self.fsw
        out[("mem",)] = self.mem
        for k, t in self.stack.items():
            out[("s", k)] = t
        for i, t in enumerate(reversed(self.fpu)):
            out[("st", i)] = t
        for i, term in enumerate(self.layer_terms):
            out[("layer", i)] = term
        return out


@dataclass
class Exit:
    kind: str  # "branch", "ret", "switch", "tail"
    state: State
    index: int = -1  # instruction index of the terminator
    cond: tuple | None = None  # (cc, flags term) for "branch"
    targets: tuple = ()  # instruction indices: (taken, fallthrough) or the switch cases
    switch_index: int | None = None
    ret_pop: int = 0


class Side:
    """Symbolic execution of one listing."""

    def __init__(
        self,
        terms: Terms,
        listing: Listing,
        tag: str,
        callee: Callable[[str], CalleeInfo | None],
        names: dict[str, int],
        tail_name: Callable[[int], str | None] = lambda _: None,
    ) -> None:
        self.t = terms
        self.lst = listing
        self.tag = tag
        self.callee = callee
        self.names = (
            names  # replacement text -> address, to recognise this function's tables
        )
        self.tail_name = (
            tail_name  # tail call target address -> a name both sides share
        )

    # -- values ---------------------------------------------------------------------------
    def name_term(self, text: str) -> int:
        addr = self.names.get(text)
        if addr is not None and addr in self.lst.data_tables:
            return self.t.sym("datatable", self.lst.data_tables[addr])
        return self.t.sym("name", text)

    def address(self, st: State, m: Mem) -> int:
        base, index, scale, disp, names = m.base
        t = self.t
        a = t.const(disp)
        if base is not None:
            a = t.add(a, self.read_reg(st, Reg(base, "full")))
        if index is not None:
            a = t.add(a, t.scale(self.read_reg(st, Reg(index, "full")), scale))
        for n in names:
            a = t.add(a, self.name_term(n))
        if m.segment is not None:
            a = t.op("seg:" + m.segment, a)
        return a

    def read_reg(self, st: State, r: Reg) -> int:
        full = st.regs[r.name]
        return full if r.kind == "full" else self.part(full, r.kind)

    def part(self, full: int, kind: str) -> int:
        """The low byte, second byte or low word of a 32-bit term."""
        head, data, children = self.t.nodes[full]
        if head == "c":
            return self.t.const(
                {"lo8": data & 0xFF, "hi8": (data >> 8) & 0xFF, "lo16": data & 0xFFFF}[
                    kind
                ]
            )
        if head == "op":
            if data in ("zx8", "sx8") and kind == "lo8":
                return children[0]
            if data in ("zx16", "sx16") and kind == "lo16":
                return children[0]
            if data == "ins_" + kind:
                return children[1]
            if data == "ins_lo16":
                return self.t.op(kind, children[1])
            if (
                data == "ins_lo8"
                and kind == "hi8"
                or data == "ins_hi8"
                and kind == "lo8"
            ):
                return self.part(children[0], kind)
        return self.t.op(kind, full)

    def write_reg(self, st: State, r: Reg, value: int) -> None:
        if r.name == "esp" and r.kind != "full":
            raise NotEquivalent("partial write to esp")
        if r.kind == "full":
            st.regs[r.name] = value
            return
        old = st.regs[r.name]
        zero = self.t.value_of(old) == 0
        if zero and r.kind == "lo8":
            st.regs[r.name] = self.t.op("zx8", value)
        elif zero and r.kind == "lo16":
            st.regs[r.name] = self.t.op("zx16", value)
        else:
            st.regs[r.name] = self.t.op("ins_" + r.kind, old, value)

    def extract(self, value: int, start: int, size: int, whole: int) -> int:
        """Bytes [start, start + size) of a value `whole` bytes wide."""
        if start == 0 and size == whole:
            return value
        c = self.t.value_of(value)
        if c is not None:
            return self.t.const((c >> (8 * start)) & ((1 << (8 * size)) - 1))
        return self.t.op("bytes", value, self.t.const(start), self.t.const(size))

    def stack_read(self, st: State, off: int, size: int) -> int:
        key = (off, size)
        if key in st.stack:
            return st.stack[key]
        overlap = sorted(k for k in st.stack if k[0] < off + size and off < k[0] + k[1])
        if overlap:
            # assemble the value from the pieces that cover it, each named relative to the read
            # so that the same bytes give the same term wherever the frame puts them
            pieces = []
            pos = off
            for k0, ksize in overlap:
                if k0 > pos:
                    pieces.append(
                        (pos - off, k0 - pos, self.stack_base(st, pos, k0 - pos))
                    )
                    pos = k0
                lo, hi = max(k0, pos), min(k0 + ksize, off + size)
                if hi > lo:
                    pieces.append(
                        (
                            lo - off,
                            hi - lo,
                            self.extract(
                                st.stack[(k0, ksize)], lo - k0, hi - lo, ksize
                            ),
                        )
                    )
                    pos = hi
            if pos < off + size:
                pieces.append(
                    (
                        pos - off,
                        off + size - pos,
                        self.stack_base(st, pos, off + size - pos),
                    )
                )
            if len(pieces) == 1:
                return pieces[0][2]
            return self.t.op(
                "concat",
                *(self.t.const(start * 64 + n) for start, n, _ in pieces),
                *(v for _, _, v in pieces),
            )
        return self.stack_base(st, off, size)

    def stack_base(self, st: State, off: int, size: int) -> int:
        """A slot no write in this function has covered: what was there before."""
        for (_, floor), term in zip(st.layers, st.layer_terms):
            if off >= floor and off != 0:
                return self.t.op(
                    "slot_after", self.t.const(off), self.t.const(size), term
                )
        if off >= 0:
            return self.t.sym("stack_in", off, size)
        # Never written: an unspecified value. Both sides read the same unspecified value of
        # a size, so that code that reads an uninitialised local in the same way compares equal.
        return self.t.mk("undef", ("stack", size))

    def stack_write(self, st: State, off: int, size: int, value: int) -> None:
        for k in [
            k
            for k in st.stack
            if k[0] < off + size and off < k[0] + k[1] and k != (off, size)
        ]:
            # keep the bytes of the old value this write does not cover
            old = st.stack.pop(k)
            k0, kend = k[0], k[0] + k[1]
            if k0 < off:
                st.stack[(k0, off - k0)] = self.extract(old, 0, off - k0, k[1])
            if kend > off + size:
                st.stack[(off + size, kend - off - size)] = self.extract(
                    old, off + size - k0, kend - off - size, k[1]
                )
        st.stack[(off, size)] = value
        st.written = st.written | {(off, size)}

    def load(self, st: State, m: Mem) -> int:
        a = self.address(st, m)
        off = self.t.stack_offset(a)
        if off is not None and m.segment is None:
            return self.stack_read(st, off, m.size)
        if self.t.has_esp[a]:
            # an indexed read from a local array: depends on everything at or above its base
            return self.t.op("stack_dyn", a, self.t.const(m.size), self.region(st, a))
        if st.escape_floor is not None:
            # a pointer into the frame is out: this load may read a local through it
            return self.t.mk(
                "load", m.size, (a, st.mem, self.pointee(st, st.escape_floor))
            )
        return self.t.mk("load", m.size, (a, st.mem))

    def region(self, st: State, a: int) -> int:
        """A term for the contents of the frame at and above the base of the indexed address `a`.
        An array is indexed upwards from its base, so nothing below it can be reached; the margin
        covers an index with a small negative constant folded into the displacement."""
        floor = self.floor(a)
        slots = sorted((k, v) for k, v in st.stack.items() if k[0] >= floor)
        return self.t.op(
            "frame",
            self.t.const(floor),
            *(self.t.const(k[0] * 64 + k[1]) for k, _ in slots),
            *(v for _, v in slots),
            *st.layer_terms,
        )

    def floor(self, a: int) -> int:
        """The lowest stack offset an address computed from esp may reach: below the constant
        part by a margin for a small negative index, or anywhere when it is not esp plus an
        offset and an index (a pointer a callee returned, say)."""
        const, coefs = self.t.as_lin(a)
        if coefs.get(self.t.esp0) != 1:
            return ANYWHERE
        return _signed(const) - 0x40

    def clobber(self, st: State, floor: int, term: int) -> None:
        """Slots at or above `floor` may have changed in a way `term` describes. `term` must
        depend on what those slots held before. The layer is merged with an older one into one
        that reaches from the lower floor, so a loop that writes on every iteration keeps a
        fixed shape."""
        if st.layers:
            floor = min(floor, st.layers[0][1])
            term = self.t.op("layers", term, *st.layer_terms)
        st.layers = (("clobber", floor),)
        st.layer_terms = [term]
        # The return address, the callee-saved registers the prologue pushed and the /GS cookie
        # are assumed to survive: overwriting them would be a buffer overflow, not a behaviour
        # to compare.
        saved = self.saved_entry()
        st.stack = {
            k: v
            for k, v in st.stack.items()
            if k[0] < floor or k[0] == 0 or v in saved or self.is_cookie(v)
        }

    def saved_entry(self) -> set[int]:
        return {self.t.sym("in", r) for r in CALLEE_SAVED}

    def pointer_floor(self, value: int) -> int:
        """The lowest stack offset a pointer into the frame may reach (ANYWHERE when the value
        is not plainly one)."""
        off = self.t.stack_offset(value)
        return off if off is not None else self.floor(value)

    def escape(self, st: State, value: int) -> None:
        """A value computed from esp reaches memory or a callee. When it is a pointer into the
        frame (esp plus an offset and perhaps an index), what it points to is visible to every
        call from now on."""
        st.escaped = True
        if self.is_cookie(value):
            return  # esp mixed into the /GS cookie: not a pointer
        floor = self.pointer_floor(value)
        if floor == ANYWHERE and st.escape_floor is not None:
            # not plainly esp + offset: a value a callee or a load produced from a pointer we
            # handed out, which can only point into what has already escaped
            return
        st.escape_floor = (
            floor if st.escape_floor is None else min(st.escape_floor, floor)
        )

    def pointee(self, st: State, floor: int) -> int:
        """The part of the frame a callee can read through a pointer to `floor`: every slot
        from there up, named relative to the pointer so that the same object at another place
        in the frame compares equal. The return address, the callee-saved registers and the
        /GS cookie are not the function's data and are left out."""
        saved = self.saved_entry()
        slots = sorted(
            (k, v)
            for k, v in st.stack.items()
            if k[0] >= floor and k[0] != 0 and v not in saved and not self.is_cookie(v)
        )
        return self.t.op(
            "pointee",
            *(self.t.const((k[0] - floor) * 64 + k[1]) for k, _ in slots),
            *(v for _, v in slots),
            *st.layer_terms,
        )

    def store(self, st: State, m: Mem, value: int) -> None:
        a = self.address(st, m)
        off = self.t.stack_offset(a)
        if off is not None and m.segment is None:
            if off == 0:
                raise NotEquivalent("write to the return address")
            self.stack_write(st, off, m.size, value)
            return
        if self.t.has_esp[a]:
            # an indexed write into a local array: everything at or above its base may change
            if self.t.has_esp[value]:
                self.escape(st, value)
            term = self.t.op(
                "dyn_write", a, self.t.const(m.size), value, self.region(st, a)
            )
            self.clobber(st, self.floor(a), term)
            return
        if self.t.has_esp[value]:
            self.escape(st, value)
        if st.escape_floor is not None:
            # the pointer written through may be one to a local
            before = self.pointee(st, st.escape_floor)
            st.mem = self.t.mk("store", m.size, (st.mem, a, value))
            self.clobber(st, st.escape_floor, self.t.op("store_into", st.mem, before))
            return
        st.mem = self.t.mk("store", m.size, (st.mem, a, value))

    def read(self, st: State, o: Operand) -> int:
        if isinstance(o, Reg):
            return self.read_reg(st, o)
        if isinstance(o, Imm):
            return self.t.const(o.value)
        if isinstance(o, Name):
            return self.name_term(o.text)
        if isinstance(o, Mem):
            return self.load(st, o)
        raise NotEquivalent(f"cannot read operand {o}")

    def write(self, st: State, o: Operand, value: int) -> None:
        if isinstance(o, Reg):
            self.write_reg(st, o, value)
        elif isinstance(o, Mem):
            self.store(st, o, value)
        else:
            raise NotEquivalent(f"cannot write operand {o}")

    @staticmethod
    def size_of(o: Operand) -> int:
        if isinstance(o, Reg):
            return o.size
        if isinstance(o, Mem):
            return o.size
        return 4

    # -- stack pointer --------------------------------------------------------------------
    def esp(self, st: State) -> int:
        off = self.t.stack_offset(st.regs["esp"])
        if off is None:
            raise NotEquivalent("esp is not a constant offset from its entry value")
        return off

    def push(self, st: State, value: int) -> None:
        off = self.esp(st) - 4
        st.regs["esp"] = self.t.add(self.t.esp0, self.t.const(off))
        self.stack_write(st, off, 4, value)

    def pop(self, st: State) -> int:
        off = self.esp(st)
        value = self.stack_read(st, off, 4)
        st.regs["esp"] = self.t.add(self.t.esp0, self.t.const(off + 4))
        st.call_level = max(st.call_level, off + 4)
        return value

    # -- flags ----------------------------------------------------------------------------
    def set_flags(self, st: State, kind: str, *children: int) -> None:
        if kind.startswith("test"):
            children = tuple(sorted(children))
        st.flags = self.t.mk("flags", kind, tuple(children))

    def condition(self, st: State, cc: str) -> tuple[str, int]:
        """The condition `cc` on the current flags, in a canonical form."""
        head, kind, children = self.t.nodes[st.flags]
        if (
            head == "flags"
            and kind.startswith("cmp")
            and cc in MIRROR
            and children[0] > children[1]
        ):
            return MIRROR[cc], self.t.mk("flags", kind, (children[1], children[0]))
        return cc, st.flags

    def cond_term(self, st: State, cc: str) -> int:
        cc, flags = self.condition(st, cc)
        return self.t.op("cond_" + cc, flags)

    # -- calls ----------------------------------------------------------------------------
    def is_cookie(self, value: int) -> bool:
        """The /GS cookie as the epilogue passes it on: a value xor-ed with esp."""
        head, name, children = self.t.nodes[value]
        return (
            head == "op"
            and name == "xor4"
            and any(self.t.stack_offset(c) is not None for c in children)
        )

    def call(
        self,
        st: State,
        target: int,
        target_text: str | None,
        ins_index: int,
        tail: bool,
    ) -> None:
        t = self.t
        info = self.callee(target_text) if target_text is not None else None
        cookie_check = target_text == CHECK_PLACEHOLDER and self.is_cookie(
            st.regs["ecx"]
        )
        if cookie_check:
            # __security_check_cookie(ecx): __fastcall. The placeholder can stand for another
            # call too, so only a cookie actually passed in ecx says which one this is.
            info = CalleeInfo(pops=0, reads_ecx=True, reads_edx=False)
        kept = (st.regs["eax"], st.regs["edx"])
        if (
            info is None
            and target_text is not None
            and (m := STDCALL_NAME.search(target_text))
        ):
            info = CalleeInfo(pops=int(m.group(1)))
        esp = self.esp(st)
        args_from = esp + 4 if tail else esp
        if info is not None and info.pops is not None and info.pops > 0:
            nargs, pops = info.pops // 4, info.pops
        else:
            # the slots written between esp and the frame, contiguous from esp, are the arguments;
            # a callee-saved register pushed by the prologue is not one
            saved = {t.sym("in", r) for r in CALLEE_SAVED}
            nargs = 0
            while (
                (args_from + 4 * nargs, 4) in st.written
                and args_from + 4 * nargs < st.call_level
                and st.stack.get((args_from + 4 * nargs, 4)) not in saved
            ):
                nargs += 1
            if info is not None and info.pops == 0:
                pops = 0
            else:
                pops = 4 * nargs
                nxt = (
                    self.lst.instrs[ins_index + 1]
                    if ins_index + 1 < len(self.lst.instrs)
                    else None
                )
                if (
                    nxt is not None
                    and nxt.mnemonic == "add"
                    and nxt.operands
                    and nxt.operands[0] == Reg("esp", "full")
                    and isinstance(nxt.operands[1], Imm)
                    and nxt.operands[1].value == 4 * nargs
                ):
                    pops = 0  # cdecl: the caller removes the arguments
        args = [self.stack_read(st, args_from + 4 * i, 4) for i in range(nargs)]
        inputs = [target, *args]
        if tail:
            # the callee takes over our arguments, however many it reads: every slot above the
            # return address that we have overwritten is an input
            above = sorted((k, v) for k, v in st.stack.items() if k[0] > 0)
            inputs.append(
                t.op(
                    "incoming",
                    *(t.const(k[0] * 64 + k[1]) for k, _ in above),
                    *(v for _, v in above),
                    *st.layer_terms,
                )
            )
        inputs.append(st.regs["ecx"] if info is None or info.reads_ecx else t.const(0))
        inputs.append(st.regs["edx"] if info is None or info.reads_edx else t.const(0))
        # a pointer into the frame lets the callee read the frame: those contents are inputs
        for x in list(inputs):
            if t.has_esp[x]:
                self.escape(st, x)
        if st.escape_floor is not None:
            inputs.append(self.pointee(st, st.escape_floor))
        fpu_args = list(st.fpu)
        st.mem = t.mk("call", (nargs, len(fpu_args)), (st.mem, *inputs, *fpu_args))
        st.fpu = []
        for r in ("eax", "ecx", "edx"):
            st.regs[r] = t.op("after_call_" + r, st.mem)
        if cookie_check:
            # it returns only when the cookie is intact, and leaves the return value alone
            st.regs["eax"], st.regs["edx"] = kept
        st.flags = t.op("after_call_flags", st.mem)
        if st.escape_floor is not None:
            # the call's inputs include the escaped part of the frame, so its term depends on it
            self.clobber(st, st.escape_floor, st.mem)
        if not tail:
            # a tail call leaves esp at our return address, which check_return expects
            st.regs["esp"] = t.add(t.esp0, t.const(esp + pops))
            st.frame_set = True

    # -- one instruction ------------------------------------------------------------------
    def step(self, st: State, i: int) -> Exit | int:
        """Execute instruction i. Returns the next index, or an Exit."""
        ins = self.lst.instrs[i]
        mn, ops, t = ins.mnemonic, ins.operands, self.t
        nxt = i + 1

        if mn == "nop":
            return nxt
        if mn == "jmp":
            o = ops[0]
            if ins.jump_target is not None:
                if ins.jump_target in self.lst.index_of:
                    return self.lst.index_of[ins.jump_target]
                # a tail call by displacement. The displacement differs from one jump site to
                # the next, so name the target by its address where the parser recorded one
                # A target neither database knows is compared by its displacement,
                # which is what the text diff does; a known one never equals it.
                name = self.tail_name(ins.jump_target)
                target = (
                    self.t.sym("jump", name)
                    if name is not None
                    else self.t.sym("jump_text", ins.text)
                )
                self.call(st, target, None, i, tail=True)
                return Exit("tail", st, i)
            if isinstance(o, Mem) and o.base[1] is not None and o.base[2] == 4:
                return self.switch(st, ins, i)
            # a tail call
            self.call(st, self.read(st, o), call_target_text(o), i, tail=True)
            return Exit("tail", st, i)
        if mn.startswith("j"):
            cc = mn[1:]
            if cc not in CONDITIONS or ins.jump_target is None:
                raise NotEquivalent(f"unsupported jump {ins.text}")
            if ins.jump_target not in self.lst.index_of:
                raise NotEquivalent("jump outside the listing")
            cond = self.condition(st, cc)
            taken = self.lst.index_of[ins.jump_target]
            # a condition already decided on this path: the other way cannot be reached
            if cond in st.facts:
                return taken
            if (cond[1], NEGATE[cond[0]]) in st.facts:
                return nxt
            return Exit("branch", st, i, cond, (taken, nxt))
        if mn == "ret":
            pop = ops[0].value if ops and isinstance(ops[0], Imm) else 0
            return Exit("ret", st, i, ret_pop=pop)
        if mn == "call":
            o = ops[0]
            self.call(st, self.read(st, o), call_target_text(o), i, tail=False)
            return nxt

        if mn == "mov":
            self.write(st, ops[0], self.read(st, ops[1]))
        elif mn in ("movzx", "movsx"):
            v = self.read(st, ops[1])
            kind = ("zx" if mn == "movzx" else "sx") + str(8 * self.size_of(ops[1]))
            self.write(st, ops[0], t.op(kind, v))
        elif mn == "lea":
            if not isinstance(ops[1], Mem):
                raise NotEquivalent("lea without a memory operand")
            self.write(st, ops[0], self.address(st, ops[1]))
        elif mn == "push":
            self.push(st, self.read(st, ops[0]))
        elif mn == "pop":
            v = self.pop(st)
            self.write(st, ops[0], v)
        elif mn in ("add", "sub", "adc", "sbb", "and", "or", "xor", "cmp", "test"):
            self.alu(st, mn, ops)
            if ops[0] == Reg("esp", "full"):
                if mn == "sub" and not st.frame_set:
                    # the prologue allocating the frame; a later `sub esp` makes room for arguments
                    st.call_level, st.frame_set = self.esp(st), True
                # arguments removed after a call: the next call's are pushed below this
                st.call_level = max(st.call_level, self.esp(st))
        elif mn in ("inc", "dec", "neg", "not"):
            a = self.read(st, ops[0])
            size = self.size_of(ops[0])
            if size == 4 and mn != "not":
                r = {
                    "inc": lambda: t.add(a, t.const(1)),
                    "dec": lambda: t.add(a, t.const(1), -1),
                    "neg": lambda: t.scale(a, -1),
                }[mn]()
            else:
                r = t.op(f"{mn}{size}", a)
            if mn != "not":
                self.set_flags(st, mn + str(size), a, st.flags)
            self.write(st, ops[0], r)
        elif mn in ("shl", "sal", "shr", "sar", "rol", "ror"):
            a = self.read(st, ops[0])
            size = self.size_of(ops[0])
            n = self.read(st, ops[1]) if len(ops) > 1 else t.const(1)
            k = t.value_of(n)
            if mn in ("shl", "sal") and size == 4 and k is not None:
                r = t.scale(a, 1 << (k & 31))
            else:
                r = t.op(f"{mn}{size}", a, n)
            self.set_flags(st, f"{mn}{size}", a, n)
            self.write(st, ops[0], r)
        elif mn == "imul" and len(ops) >= 2:
            a = self.read(st, ops[1] if len(ops) == 3 else ops[0])
            b = self.read(st, ops[2] if len(ops) == 3 else ops[1])
            size = self.size_of(ops[0])
            kb, ka = t.value_of(b), t.value_of(a)
            if size == 4 and kb is not None:
                r = t.scale(a, kb)
            elif size == 4 and ka is not None:
                r = t.scale(b, ka)
            else:
                r = t.op(f"imul{size}", a, b, commutative=True)
            self.set_flags(st, f"imul{size}", *sorted((a, b)))
            self.write(st, ops[0], r)
        elif mn in ("mul", "imul", "div", "idiv"):
            if self.size_of(ops[0]) != 4:
                raise NotEquivalent(f"narrow {mn}")
            src = self.read(st, ops[0])
            eax, edx = st.regs["eax"], st.regs["edx"]
            if mn in ("mul", "imul"):
                st.regs["eax"] = t.op(mn + "_lo", eax, src, commutative=True)
                st.regs["edx"] = t.op(mn + "_hi", eax, src, commutative=True)
            else:
                st.regs["eax"] = t.op(mn + "_q", edx, eax, src)
                st.regs["edx"] = t.op(mn + "_r", edx, eax, src)
            self.set_flags(st, mn, st.regs["eax"], st.regs["edx"])
        elif mn == "cdq":
            st.regs["edx"] = t.op("cdq", st.regs["eax"])
        elif mn.startswith("set") and mn[3:] in CONDITIONS:
            self.write(st, ops[0], self.cond_term(st, mn[3:]))
        elif mn == "xchg":
            a, b = self.read(st, ops[0]), self.read(st, ops[1])
            self.write(st, ops[0], b)
            self.write(st, ops[1], a)
        elif mn.startswith("rep ") or mn.startswith("repe ") or mn.startswith("repne "):
            self.string_op(st, mn)
        elif mn.startswith("f"):
            self.fpu(st, mn, ops)
        else:
            raise NotEquivalent(f"unsupported instruction {ins.text}")
        return nxt

    def alu(self, st: State, mn: str, ops: list[Operand]) -> None:
        t = self.t
        size = self.size_of(ops[0])
        a = self.read(st, ops[0])
        b = self.read(st, ops[1])
        if mn in ("xor", "sub") and ops[0] == ops[1] and isinstance(ops[0], Reg):
            r = t.const(0)
            self.set_flags(st, "zero")
        elif mn in ("cmp", "sub"):
            r = t.add(a, b, -1) if size == 4 else t.op(f"sub{size}", a, b)
            self.set_flags(st, f"cmp{size}", a, b)
        elif mn in ("and", "test"):
            r = t.op(f"and{size}", a, b, commutative=True)
            self.set_flags(st, f"test{size}", a, b)
        elif mn == "add":
            r = t.add(a, b) if size == 4 else t.op(f"add{size}", a, b, commutative=True)
            self.set_flags(st, f"add{size}", *sorted((a, b)))
        elif mn in ("or", "xor"):
            r = t.op(f"{mn}{size}", a, b, commutative=True)
            self.set_flags(st, f"{mn}{size}", *sorted((a, b)))
        else:  # adc, sbb read the carry
            r = t.op(f"{mn}{size}", a, b, st.flags)
            self.set_flags(st, f"{mn}{size}", a, b, st.flags)
        if mn not in ("cmp", "test"):
            if (
                isinstance(ops[0], Reg)
                and ops[0].name == "esp"
                and t.stack_offset(r) is None
            ):
                raise NotEquivalent("esp no longer a constant offset")
            self.write(st, ops[0], r)

    def string_op(self, st: State, mn: str) -> None:
        t = self.t
        for r in ("edi", "esi"):
            if t.has_esp[st.regs[r]]:
                raise NotEquivalent("string instruction on the stack frame")
        inputs = (
            st.mem,
            st.regs["ecx"],
            st.regs["esi"],
            st.regs["edi"],
            st.regs["eax"],
        )
        st.mem = t.mk("string", mn, inputs)
        for r in ("ecx", "esi", "edi"):
            st.regs[r] = t.op("after_" + r, st.mem)
        if "cmps" in mn or "scas" in mn:
            st.flags = t.op("after_flags", st.mem)

    def switch(self, st: State, ins: Instr, i: int) -> Exit:
        m = ins.operands[0]
        assert isinstance(m, Mem)
        base, index, _scale, disp, names = m.base
        addr = None
        if len(names) == 1:
            addr = self.names.get(names[0])
        elif not names:
            addr = disp
        if addr not in self.lst.jump_tables:
            if names and addr is not None:
                # a table of function pointers elsewhere in the image: a tail call through it
                self.call(st, self.load(st, m), None, i, tail=True)
                return Exit("tail", st, i)
            if len(self.lst.jump_tables) != 1:
                raise NotEquivalent("cannot tell which jump table a switch uses")
            addr = next(iter(self.lst.jump_tables))
        targets = self.lst.jump_tables[addr]
        idx = (
            self.t.const(0) if index is None else self.read_reg(st, Reg(index, "full"))
        )
        if base is not None:
            idx = self.t.add(idx, self.read_reg(st, Reg(base, "full")))
        out = []
        for target in targets:
            if target not in self.lst.index_of:
                raise NotEquivalent("jump table target outside the listing")
            out.append(self.lst.index_of[target])
        return Exit("switch", st, i, targets=tuple(out), switch_index=idx)

    # -- x87 ------------------------------------------------------------------------------
    def st_get(self, st: State, i: int) -> int:
        if i < len(st.fpu):
            return st.fpu[-1 - i]
        # below the values we pushed: a float returned by a call
        return self.t.op("fpu_in", self.t.const(i - len(st.fpu)), st.mem)

    def st_set(self, st: State, i: int, v: int) -> None:
        while i >= len(st.fpu):
            st.fpu.insert(0, self.st_get(st, len(st.fpu)))
        st.fpu[-1 - i] = v

    def fpop(self, st: State) -> int:
        v = self.st_get(st, 0)
        if st.fpu:
            st.fpu.pop()
        return v

    def fpu(self, st: State, mn: str, ops: list[Operand]) -> None:
        t = self.t
        if mn in ("fld", "fild"):
            o = ops[0]
            v = self.st_get(st, o.index) if isinstance(o, Fpu) else self.read(st, o)
            if mn == "fild":
                v = t.op(f"i2f{self.size_of(o)}", v)
            elif isinstance(o, Mem):
                v = t.op(f"f{o.size}", v)
            st.fpu.append(v)
        elif mn in ("fld1", "fldz", "fldpi"):
            st.fpu.append(t.sym("fconst", mn))
        elif mn in ("fst", "fstp", "fist", "fistp"):
            o = ops[0]
            v = self.st_get(st, 0)
            if isinstance(o, Fpu):
                self.st_set(st, o.index, v)
            else:
                self.write(st, o, t.op(f"{mn.rstrip('p')}{self.size_of(o)}", v))
            if mn.endswith("p"):
                self.fpop(st)
        elif mn == "fxch":
            k = fpu_index(ops[0]) if ops else 1
            a, b = self.st_get(st, 0), self.st_get(st, k)
            self.st_set(st, 0, b)
            self.st_set(st, k, a)
        elif mn in ("fchs", "fabs", "fsqrt", "frndint"):
            self.st_set(st, 0, t.op(mn, self.st_get(st, 0)))
        elif mn in ("fcom", "fcomp", "fucom", "fucomp", "ficom", "ficomp"):
            o = ops[0] if ops else Fpu(1)
            b = self.st_get(st, o.index) if isinstance(o, Fpu) else self.read(st, o)
            st.fsw = t.op(mn.rstrip("p"), self.st_get(st, 0), b)
            if mn.endswith("p"):
                self.fpop(st)
        elif mn in ("fcompp", "fucompp"):
            st.fsw = t.op(mn[:-2], self.st_get(st, 0), self.st_get(st, 1))
            self.fpop(st)
            self.fpop(st)
        elif mn == "fnstsw":
            self.write(st, ops[0], t.op("fsw", st.fsw))
        elif mn.rstrip("p") in (
            "fadd",
            "fmul",
            "fsub",
            "fsubr",
            "fdiv",
            "fdivr",
            "fiadd",
            "fimul",
            "fisub",
            "fisubr",
            "fidiv",
            "fidivr",
        ):
            base = mn.rstrip("p") if mn not in ("fsubrp", "fdivrp") else mn[:-1]
            comm = base in ("fadd", "fmul", "fiadd", "fimul")
            popping = mn.endswith("p") and mn not in ("fsubr", "fdivr")
            if not ops or (
                popping and len(ops) <= 2 and all(isinstance(o, Fpu) for o in ops)
            ):
                k = fpu_index(ops[0]) if ops else 1
                r = t.op(base, self.st_get(st, k), self.st_get(st, 0), commutative=comm)
                self.st_set(st, k, r)
                if popping:
                    self.fpop(st)
            elif len(ops) == 1:
                src = ops[0]
                v = self.read(st, src)
                r = t.op(
                    base + str(self.size_of(src)),
                    self.st_get(st, 0),
                    v,
                    commutative=comm,
                )
                self.st_set(st, 0, r)
            elif len(ops) == 2 and all(isinstance(o, Fpu) for o in ops):
                d, s = fpu_index(ops[0]), fpu_index(ops[1])
                r = t.op(base, self.st_get(st, d), self.st_get(st, s), commutative=comm)
                self.st_set(st, d, r)
            else:
                raise NotEquivalent(f"unsupported x87 form {mn}")
        else:
            raise NotEquivalent(f"unsupported x87 instruction {mn}")

    def run(self, st: State, i: int, budget: list[int]) -> Exit:
        while True:
            budget[0] -= 1
            if budget[0] < 0:
                raise NotEquivalent("instruction budget exhausted")
            if i >= len(self.lst.instrs):
                raise NotEquivalent("ran off the end of the listing")
            try:
                r = self.step(st, i)
            except NotEquivalent as e:
                ins = self.lst.instrs[i]
                raise NotEquivalent(
                    f"{e} [{self.tag} {ins.addr:#x}: {ins.text}]"
                ) from e
            if isinstance(r, Exit):
                return r
            i = r


