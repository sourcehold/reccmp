"""Decide whether two functions do the same thing although their instructions differ.

The text diff cannot tell a real difference from one that only changes *where* the compiler kept
a value. Two compiles of the same source routinely differ that way: a value lives in `ecx` on one
side and in `eax` on the other, two independent loads come in the other order, a local gets a
different stack slot, a conditional jump is inverted with its two successors swapped, or a block
that one side shares is written out twice on the other. None of this changes what the function
does, and the existing effective-match test (`fixes.find_effective_match`) only covers the
simplest case, a same-length listing whose lines agree once every register name is blanked.

This module checks the stronger property directly. It executes both listings symbolically, side by
side, and accepts them only if they make the same observable decisions:

* the same sequence of memory writes and calls (target, arguments, `this`), in the same order;
* the same branch decisions, compared as conditions on the computed values;
* the same return value, and the callee-saved registers and `esp` restored on return.

Everything else - which register or stack slot holds a value, the order of independent loads,
the layout of the blocks - is free to differ.

How it works. Values are terms (hash-consed tuples) over the function's inputs, so two
computations are equal when they build the same term. Sums are kept in a canonical linear form and
commutative operations sort their operands, so `[esi+edi+8]` equals `[edi+esi+8]` and `a+b` equals
`b+a`. Each side is run from a pair of start points to its next conditional branch, `ret` or
switch, following unconditional jumps. The pair of end points then gives the successor pairs:
taken with taken and fall-through with fall-through, or crossed over when one side has the
inverted condition. Where a pair of start points is reached along several paths (a loop, a merge),
two locations are only treated as holding the same value if they hold equal terms on *every*
incoming path; the state at each pair is recomputed until that relation stops shrinking (a greatest
fixpoint), so loops are handled soundly.

Assumptions, all of them about code generated by a compiler rather than written to be devious:

* a callee reads its stack arguments, `ecx`/`edx` if its own code reads them before writing
  them, and memory; and it returns the same results for the same inputs;
* a callee only touches the caller's frame through a pointer the caller gave away; once any
  stack address escapes, every call is taken to clobber every local;
* code is not self-modifying and does not read its own return address.

Anything the checker does not model makes it answer "not equivalent", so a gap costs a missed
effective match, never a wrong one.
"""

