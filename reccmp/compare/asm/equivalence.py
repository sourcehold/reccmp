def call_target_text(o: "Operand") -> str | None:
    """The name of a call target: `call Name` or `call dword ptr [Name]` (an import)."""
    if isinstance(o, Name):
        return o.text
    if (
        isinstance(o, Mem)
        and o.base[0] is None
        and o.base[1] is None
        and len(o.base[4]) == 1
    ):
        return o.base[4][0]
    return None


class NotEquivalent(Exception):
    """The listings differ in an observable way, or in a way the checker cannot model."""


class Terms:
    """Hash-consed terms. A term is an int id for a node (head, data, children)."""

    def __init__(self) -> None:
        self.ids: dict[tuple, int] = {}
        self.nodes: list[tuple] = []
        self.closed: list[bool] = []
        self.has_esp: list[bool] = []
        self.esp0 = self.mk("sym", ESP0)

    def mk(self, head: str, data=None, children: tuple = ()) -> int:
        key = (head, data, children)
        found = self.ids.get(key)
        if found is not None:
            return found
        tid = len(self.nodes)
        self.ids[key] = tid
        self.nodes.append(key)
        self.closed.append(
            head not in ("local", "undef") and all(self.closed[c] for c in children)
        )
        # A value read from memory or returned by a call is not taken to be computed from esp,
        # even when its term mentions the frame: a pointer into the frame only gets there by
        # escaping first, and the escape is what accounts for it.
        opaque = (
            head in OPAQUE_HEADS
            or head == "op"
            and (data in OPAQUE_OPS or data.startswith("after_"))
        )
        self.has_esp.append(
            (head == "sym" and data == ESP0)
            or not opaque
            and any(self.has_esp[c] for c in children)
        )
        return tid

    def const(self, value: int) -> int:
        return self.mk("c", value & MASK)

    def sym(self, *name) -> int:
        return self.mk("sym", tuple(name))

    def value_of(self, t: int) -> int | None:
        head, data, _ = self.nodes[t]
        return data if head == "c" else None

    # -- linear forms: const + sum(coef * term), all mod 2^32 -----------------------------
    def as_lin(self, t: int) -> tuple[int, dict[int, int]]:
        head, data, children = self.nodes[t]
        if head == "c":
            return data, {}
        if head == "lin":
            const, coefs = data
            return const, dict(zip(children, coefs))
        return 0, {t: 1}

    def lin(self, const: int, coefs: dict[int, int]) -> int:
        const &= MASK
        items = sorted((t, c & MASK) for t, c in coefs.items() if c & MASK)
        if not items:
            return self.const(const)
        if const == 0 and len(items) == 1 and items[0][1] == 1:
            return items[0][0]
        return self.mk(
            "lin", (const, tuple(c for _, c in items)), tuple(t for t, _ in items)
        )

    def add(self, a: int, b: int, sign: int = 1) -> int:
        ca, da = self.as_lin(a)
        cb, db = self.as_lin(b)
        out = dict(da)
        for t, c in db.items():
            out[t] = out.get(t, 0) + sign * c
        return self.lin(ca + sign * cb, out)

    def scale(self, a: int, k: int) -> int:
        ca, da = self.as_lin(a)
        return self.lin(ca * k, {t: c * k for t, c in da.items()})

    def op(self, name: str, *children: int, commutative: bool = False) -> int:
        if commutative:
            children = tuple(sorted(children))
        return self.mk("op", name, tuple(children))

    def stack_offset(self, t: int) -> int | None:
        """The offset from the entry `esp` if `t` is exactly esp0 + constant."""
        const, coefs = self.as_lin(t)
        if coefs == {self.esp0: 1}:
            return const - (1 << 32) if const & 0x80000000 else const
        return None


# -- parsing the reccmp listing ----------------------------------------------------------------


@dataclass(frozen=True)
class Reg:
    name: str  # full 32-bit register
    kind: str  # "full", "lo8", "hi8", "lo16"

    @property
    def size(self) -> int:
        return SIZE_OF_KIND.get(self.kind, 4)


@dataclass(frozen=True)
class Mem:
    size: int
    base: (
        tuple  # (register or None, index register or None, scale, displacement, names)
    )
    segment: str | None


@dataclass(frozen=True)
class Imm:
    value: int


@dataclass(frozen=True)
class Name:
    text: str


@dataclass(frozen=True)
class Fpu:
    index: int


def fpu_index(o: "Operand") -> int:
    if not isinstance(o, Fpu):
        raise NotEquivalent(f"expected an x87 register, got {o}")
    return o.index


Operand = Reg | Mem | Imm | Name | Fpu

NUM = re.compile(r"^-?(0x[0-9a-f]+|\d+)$")
SCALED = re.compile(r"^(e[a-z]{2})\*(\d)$")
FPU_REG = re.compile(r"^st\((\d)\)$")


def split_top(text: str, sep: str = ",") -> list[str]:
    """Split on `sep` outside brackets, so `Instance<int,15>::x` stays one operand."""
    parts, depth, cur = [], 0, []  # type: tuple[list[str], int, list[str]]
    for ch in text:
        if ch in "<([":
            depth += 1
        elif ch in ">)]":
            depth -= 1
        if ch == sep and depth == 0:
            parts.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
    if "".join(cur).strip():
        parts.append("".join(cur).strip())
    return parts


def parse_number(text: str) -> int | None:
    if NUM.match(text):
        return int(text, 0) if not text.startswith("-") else -int(text[1:], 0)
    return None


def parse_operand(text: str) -> Operand:
    text = text.strip()
    if text in DWORD_REGS:
        return Reg(text, "full")
    if text in SUBREGS:
        full, kind = SUBREGS[text]
        return Reg(full, kind)
    if text in ("st(0)", "st"):
        return Fpu(0)
    if m := FPU_REG.match(text):
        return Fpu(int(m.group(1)))
    if "[" in text and text.endswith("]"):
        head, _, inner = text.partition("[")
        inner = inner[:-1]
        words = head.split()
        size = PTR_SIZES.get(words[0], 4) if words else 4
        segment = None
        if head.rstrip().endswith(":"):
            segment = head.rstrip()[:-1].split()[-1]
        base = index = None
        scale, disp, names = 1, 0, []
        # split "a + b - 0x10" into signed terms, outside brackets
        terms: list[tuple[int, str]] = []
        sign, depth = 1, 0
        cur: list[str] = []
        i = 0
        while i < len(inner):
            ch = inner[i]
            if ch in "<(":
                depth += 1
            elif ch in ">)":
                depth -= 1
            if depth == 0 and inner[i : i + 3] in (" + ", " - "):
                terms.append((sign, "".join(cur).strip()))
                sign = 1 if inner[i + 1] == "+" else -1
                cur = []
                i += 3
                continue
            cur.append(ch)
            i += 1
        terms.append((sign, "".join(cur).strip()))
        for sgn, term in terms:
            if term in DWORD_REGS:
                if base is None:
                    base = term
                else:
                    index = term
            elif m := SCALED.match(term):
                index, scale = m.group(1), int(m.group(2))
            elif (v := parse_number(term)) is not None:
                disp += sgn * v
            else:
                if sgn < 0:
                    raise NotEquivalent(f"negative symbol in {text}")
                names.append(term)
        return Mem(size, (base, index, scale, disp & MASK, tuple(names)), segment)
    if (v := parse_number(text)) is not None:
        return Imm(v & MASK)
    return Name(text)


@dataclass
class Instr:
    addr: int
    mnemonic: str
    operands: list[Operand]
    text: str
    jump_target: int | None = None  # absolute address for a relative jump


@dataclass
class Listing:
    instrs: list[Instr]
    index_of: dict[int, int]
    jump_tables: dict[int, list[int]]  # table address -> absolute targets
    data_tables: dict[int, tuple[int, ...]]  # table address -> bytes
    start: int


def build_listing(asm: Iterable[tuple[int | None, str]]) -> Listing:
    rows = list(asm)
    instrs: list[Instr] = []
    jump_tables: dict[int, list[int]] = {}
    data_tables: dict[int, tuple[int, ...]] = {}
    start = next((a for a, _ in rows if a is not None), 0)
    mode, table_addr = "code", None
    table: list[int] = []

    def flush():
        if table_addr is None:
            return
        if mode == "jump":
            jump_tables[table_addr] = list(table)
        elif mode == "data":
            data_tables[table_addr] = tuple(table)

    for addr, text in rows:
        if text in ("Jump table:", "Data table:"):
            flush()
            mode, table_addr, table = (
                ("jump" if text.startswith("Jump") else "data"),
                None,
                [],
            )
            continue
        if mode == "jump":
            if table_addr is None:
                table_addr = addr
            table.append(start + int(text.split("+")[1], 16))
            continue
        if mode == "data":
            if table_addr is None:
                table_addr = addr
            table.append(int(text, 16))
            continue
        assert addr is not None
        mnemonic, _, rest = text.partition(" ")
        prefix = None
        if mnemonic in ("rep", "repe", "repne"):
            prefix = mnemonic
            mnemonic, _, rest = rest.partition(" ")
            mnemonic = prefix + " " + mnemonic
        instrs.append(Instr(addr, mnemonic, [], text))
        instrs[-1].operands = [] if not rest else _operands(mnemonic, rest)
    flush()
    index_of = {ins.addr: i for i, ins in enumerate(instrs)}
    addrs = sorted(a for a, _ in rows if a is not None)
    following = dict(zip(addrs, addrs[1:]))
    for ins in instrs:
        if (
            ins.mnemonic.startswith("j")
            and len(ins.operands) == 1
            and isinstance(ins.operands[0], Imm)
        ):
            disp = _signed(ins.operands[0].value)
            # The listing does not give instruction sizes. The next row is the next instruction
            # unless padding or a table follows the jump, so trust it only when the gap is a size
            # this jump can be encoded in, and otherwise take the encoding for its displacement.
            near = 5 if ins.mnemonic == "jmp" else 6
            nxt = following.get(ins.addr)
            if nxt is None or nxt - ins.addr not in (2, near):
                nxt = ins.addr + (2 if -128 <= disp <= 127 else near)
            ins.jump_target = (nxt + disp) & MASK
    return Listing(instrs, index_of, jump_tables, data_tables, start)


def _signed(v: int) -> int:
    return v - (1 << 32) if v & 0x80000000 else v


def _operands(mnemonic: str, rest: str) -> list[Operand]:
    if (
        mnemonic in ("call", "jmp")
        and "[" not in rest
        and rest.split()[0] not in DWORD_REGS
    ):
        v = parse_number(rest)
        return [Imm(v & MASK)] if v is not None else [Name(rest)]
    return [parse_operand(p) for p in split_top(rest)]


