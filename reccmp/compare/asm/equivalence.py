def show(t: Terms, term: int, depth: int = 4) -> str:
    """A readable rendering of a term, for the reason a comparison failed."""
    head, data, children = t.nodes[term]
    if head == "c":
        return hex(data)
    if head == "sym":
        return (
            ":".join(str(x) for x in data)
            if not isinstance(data[-1], tuple)
            else str(data[0])
        )
    if head == "local":
        return f"v{term}"
    if head == "undef":
        return f"undef{term}"
    if depth == 0:
        return "..."
    args = [show(t, c, depth - 1) for c in children]
    if head == "lin":
        const, coefs = data
        parts = [(a if k == 1 else f"{_signed(k)}*{a}") for a, k in zip(args, coefs)]
        if const:
            parts.append(
                hex(_signed(const))
                if _signed(const) >= 0
                else "-" + hex(-_signed(const))
            )
        return "(" + " + ".join(parts) + ")"
    if head in ("store", "call", "string"):
        args[0] = "M"
    name = (
        data if isinstance(data, str) else f"{head}{data if data is not None else ''}"
    )
    return f"{name}({', '.join(args)})"


def mem_events(t: Terms, mem: int) -> list[int]:
    events = []
    while t.nodes[mem][0] in ("store", "call", "string"):
        events.append(mem)
        mem = t.nodes[mem][2][0]
    events.append(mem)
    return events[::-1]


def describe_mem_difference(t: Terms, a: int, b: int) -> str:
    ea, eb = mem_events(t, a), mem_events(t, b)
    for x, y in zip(ea, eb):
        if x != y:
            return f"different memory writes or calls: {show(t, x)} | {show(t, y)}"
    return (
        f"different memory writes or calls: {len(ea) - 1} against {len(eb) - 1} events"
    )


def entry_state(t: Terms) -> State:
    st = State()
    for r in DWORD_REGS:
        st.regs[r] = t.sym("in", r)
    st.regs["esp"] = t.esp0
    st.flags = t.sym("in", "flags")
    st.fsw = t.sym("in", "fsw")
    st.mem = t.sym("in", "mem")
    return st


PairKey = tuple


def pair_key(o: State, r: State, io: int, ir: int, t: Terms) -> PairKey:
    def shape(s: State) -> tuple:
        esp = t.stack_offset(s.regs["esp"])
        if esp is None:
            raise NotEquivalent("esp unknown at a block boundary")
        # how many dwords above esp a call made now would take as arguments: paths that
        # disagree on it are kept apart, everything else about `written` is merged
        saved = {t.sym("in", r) for r in CALLEE_SAVED}
        run = 0
        while (
            run < 32
            and (esp + 4 * run, 4) in s.written
            and s.stack.get((esp + 4 * run, 4)) not in saved
        ):
            run += 1
        return (
            esp,
            len(s.fpu),
            s.escaped,
            tuple(kind for kind, _ in s.layers),
            run,
            s.call_level,
            s.frame_set,
        )

    return io, ir, shape(o), shape(r)


def check_return(t: Terms, o: State, r: State, ret: ReturnKind) -> None:
    for side in (o, r):
        if t.stack_offset(side.regs["esp"]) != 0:
            raise NotEquivalent("esp not restored at ret")
        for reg in CALLEE_SAVED:
            if side.regs[reg] != t.sym("in", reg):
                raise NotEquivalent(f"{reg} not restored at ret")
    if o.mem != r.mem:
        raise NotEquivalent(describe_mem_difference(t, o.mem, r.mem))
    if ret.eax and o.regs["eax"] != r.regs["eax"]:
        raise NotEquivalent("different return value")
    if ret.edx and o.regs["edx"] != r.regs["edx"]:
        raise NotEquivalent("different return value (edx)")
    if ret.st0:
        if not o.fpu or not r.fpu or o.fpu[-1] != r.fpu[-1]:
            raise NotEquivalent("different float return value")


class Pairing:
    """The fixpoint over pairs of start points."""

    def __init__(
        self, t: Terms, so: Side, sr: Side, ret: ReturnKind, budget: int
    ) -> None:
        self.t, self.so, self.sr, self.ret = t, so, sr, ret
        self.budget = [budget]
        self.incoming: dict[PairKey, dict] = {}

    def side(self, tag: str) -> Side:
        return self.so if tag == "o" else self.sr

    def abstract(self, key: PairKey) -> tuple[tuple, State, State]:
        """The entry states for a pair. Locations holding equal terms on every incoming edge share
        one symbol; a class that holds the same closed term on every edge keeps that term. The
        first value returned describes the abstraction, so an unchanged one needs no re-run.
        """
        t = self.t
        edges = [self.incoming[key][k] for k in sorted(self.incoming[key], key=repr)]

        def term_at(s: State, loc: tuple, tag: str) -> int:
            got = s.locations().get(loc)
            if got is not None:
                return got
            if loc[0] == "s":
                return self.side(tag).stack_read(s, loc[1][0], loc[1][1])
            return t.mk("undef", ("missing",))  # not set on this path: unspecified

        sigs: dict[tuple, list] = {}
        for tag, idx in (("o", 0), ("r", 1)):
            locs = set().union(*(e[idx].locations().keys() for e in edges))
            for loc in locs:
                sig = tuple(term_at(e[idx], loc, tag) for e in edges)
                sigs.setdefault(sig, []).append((tag, loc))
        classes = []
        for sig, members in sigs.items():
            closed = (
                sig[0] if all(x == sig[0] for x in sig) and t.closed[sig[0]] else None
            )
            classes.append((tuple(sorted(members, key=repr)), closed))
        classes.sort(key=repr)
        values: dict[tuple, int] = {}
        for n, (group, closed) in enumerate(classes):
            v = closed if closed is not None else t.mk("local", (key, n))
            for m in group:
                values[m] = v

        def build(tag: str, proto: State) -> State:
            side = 0 if tag == "o" else 1
            s = State()
            for r in DWORD_REGS:
                if r != "esp":
                    s.regs[r] = values[(tag, ("r", r))]
            s.regs["esp"] = proto.regs["esp"]
            s.flags = values[(tag, ("flags",))]
            s.fsw = values[(tag, ("fsw",))]
            s.mem = values[(tag, ("mem",))]
            s.stack = {
                loc[1]: v
                for (sd, loc), v in values.items()
                if sd == tag and loc[0] == "s"
            }
            s.fpu = [values[(tag, ("st", i))] for i in reversed(range(len(proto.fpu)))]
            s.written, s.escaped = written[tag], proto.escaped
            # escaped on some path: escaped here, from the lowest pointer on any
            floors = [
                e[side].escape_floor for e in edges if e[side].escape_floor is not None
            ]
            s.escape_floor = min(floors) if floors else None
            s.call_level, s.frame_set = proto.call_level, proto.frame_set
            s.facts = facts[tag]
            # the same kinds of layer on every edge (they are in the key); each reaches as low as
            # it does on any edge
            s.layers = tuple(
                (kind, min(e[side].layers[i][1] for e in edges))
                for i, (kind, _) in enumerate(proto.layers)
            )
            s.layer_terms = [
                values[(tag, ("layer", i))] for i in range(len(proto.layers))
            ]
            return s

        # a fact survives a merge when every incoming path established it about values
        # that do not change from one edge to the next
        facts = {}
        # the slots written on any path: a call may take its arguments
        # from any of them, so counting too many is safe where too few is not
        written = {}
        for tag, idx in (("o", 0), ("r", 1)):
            common = frozenset.intersection(*(e[idx].facts for e in edges))
            facts[tag] = frozenset(f for f in common if t.closed[f[0]])
            written[tag] = frozenset().union(*(e[idx].written for e in edges))
        o0, r0 = edges[0]
        so, sr = build("o", o0), build("r", r0)
        shape = (
            tuple(classes),
            facts["o"],
            facts["r"],
            written["o"],
            written["r"],
            so.layers,
            sr.layers,
            so.escape_floor,
            sr.escape_floor,
        )
        return shape, so, sr

    def run(self, io: int, ir: int) -> None:
        t = self.t
        key = pair_key(entry_state(t), entry_state(t), io, ir, t)
        self.incoming[key] = {("entry",): (entry_state(t), entry_state(t))}
        work = [key]
        done: dict[PairKey, tuple] = {}
        while work:
            key = work.pop()
            shape, so, sr = self.abstract(key)
            if done.get(key) == shape:
                continue
            done[key] = shape
            eo = self.so.run(so, key[0], self.budget)
            er = self.sr.run(sr, key[1], self.budget)
            for succ, states in self.successors(eo, er):
                self.incoming.setdefault(succ, {})[(key, succ)] = states
                work.append(succ)

    def successors(self, eo: Exit, er: Exit):
        t, so, sr = self.t, self.so, self.sr
        if eo.kind != er.kind:
            raise NotEquivalent(f"{eo.kind} against {er.kind}")
        o, r = eo.state, er.state
        if o.mem != r.mem:
            raise NotEquivalent(
                describe_mem_difference(t, o.mem, r.mem) + f" at {eo.index}/{er.index}"
            )
        if eo.kind in ("ret", "tail"):
            if eo.ret_pop != er.ret_pop:
                raise NotEquivalent("different ret N")
            check_return(
                t,
                o,
                r,
                ReturnKind(eax=False, edx=False) if eo.kind == "tail" else self.ret,
            )
            return []
        if eo.kind == "branch":
            assert eo.cond is not None and er.cond is not None
            (cco, flo), (ccr, flr) = eo.cond, er.cond
            if flo != flr:
                raise NotEquivalent(
                    f"different branch condition: {cco} {show(t, flo)} | {ccr} {show(t, flr)}"
                    f" at {so.lst.instrs[eo.index].addr:#x}/{sr.lst.instrs[er.index].addr:#x}"
                )
            if cco == ccr:
                pairs = [(eo.targets[0], er.targets[0]), (eo.targets[1], er.targets[1])]
            elif NEGATE[cco] == ccr:
                pairs = [(eo.targets[0], er.targets[1]), (eo.targets[1], er.targets[0])]
            else:
                raise NotEquivalent(
                    f"different branch condition: {cco} | {ccr} on {show(t, flo)}"
                    f" at {so.lst.instrs[eo.index].addr:#x}/{sr.lst.instrs[er.index].addr:#x}"
                )
            # each way out knows which way the branch went; the flags are the same term on
            # both sides, so the same fact, in the original's terms, holds on both
            out = []
            for taken, (a, b) in zip((True, False), pairs):
                fact = (flo, cco if taken else NEGATE[cco])
                o2, r2 = o.copy(), r.copy()
                o2.facts, r2.facts = o.facts | {fact}, r.facts | {fact}
                out.append((pair_key(o2, r2, a, b, t), (o2, r2)))
            return out
        if eo.switch_index != er.switch_index or len(eo.targets) != len(er.targets):
            raise NotEquivalent("different switch")
        pairs = sorted(set(zip(eo.targets, er.targets)))
        return [(pair_key(o, r, a, b, t), (o, r)) for a, b in pairs]


def find_semantic_match(
    orig: Iterable[tuple[int | None, str]],
    recomp: Iterable[tuple[int | None, str]],
    *,
    callee: Callable[[str], CalleeInfo | None] = lambda _: None,
    orig_names: dict[str, int] | None = None,
    recomp_names: dict[str, int] | None = None,
    tail_name: Callable[[ImageId, int], str | None] = lambda _img, _addr: None,
    returns: ReturnKind = ReturnKind(),
    budget: int = 200_000,
) -> tuple[bool, str]:
    """Are the two listings equivalent? Returns (verdict, reason when not).

    `callee` describes the function a call goes to, by the call's operand text.
    `*_names` map the placeholder or name the parser put in an operand back to its address, which
    is how a switch finds its jump table and a load finds a data table of this function.
    `tail_name` names the function a tail call jumps to, from its absolute address in the given
    image; the two sides must give the same name for the same function. When some target has
    no name, all of them are compared by displacement, as the text diff does.
    `returns` says which registers hold the return value."""
    try:
        t = Terms()
        lo, lr = build_listing(orig), build_listing(recomp)
        # Name tail call targets only when every one on both sides has a name; otherwise
        # compare them all by displacement, as the text diff does, so that a target one
        # side can name and the other cannot is not taken for a difference.
        names = {
            img: {
                ins.jump_target: tail_name(img, ins.jump_target)
                for ins in lst.instrs
                if ins.mnemonic == "jmp"
                and ins.jump_target is not None
                and ins.jump_target not in lst.index_of
            }
            for img, lst in ((ImageId.ORIG, lo), (ImageId.RECOMP, lr))
        }
        if any(n is None for m in names.values() for n in m.values()):
            names = {ImageId.ORIG: {}, ImageId.RECOMP: {}}
        so = Side(t, lo, "o", callee, orig_names or {}, names[ImageId.ORIG].get)
        sr = Side(t, lr, "r", callee, recomp_names or {}, names[ImageId.RECOMP].get)
        if not so.lst.instrs or not sr.lst.instrs:
            return False, "empty listing"
        Pairing(t, so, sr, returns, budget).run(0, 0)
        return True, ""
    except NotEquivalent as e:
        return False, str(e)
    except (KeyError, IndexError, ValueError, AttributeError) as e:
        return False, f"unmodelled: {type(e).__name__}: {e}"


def return_kind_from_symbol(symbol: str | None) -> ReturnKind:
    """Which registers carry the return value, read off an MSVC decorated name."""
    if not symbol or not symbol.startswith("?"):
        return ReturnKind()
    if symbol.startswith("??0"):
        return ReturnKind(eax=True, edx=False)  # constructors return this
    name_end = symbol.find("@@")
    if name_end < 0:
        return ReturnKind()
    rest = symbol[name_end + 2 :]
    if not rest:
        return ReturnKind()
    kind = rest[0]
    i = 1
    if kind in "ABEFIJMNQRUV":  # non-static member: a cv qualifier for this
        i += 1
    elif kind not in "CDKLSTYZ":
        return ReturnKind()
    i += 1  # calling convention
    if rest[i : i + 2] == "?A":
        i += 2
    ret = rest[i : i + 2]
    if ret.startswith("X"):
        return ReturnKind(eax=False, edx=False)
    if ret.startswith("@"):  # constructor/destructor without return type
        return ReturnKind(eax=True, edx=False)
    if ret in ("_J", "_K"):
        return ReturnKind(eax=True, edx=True)
    if ret[:1] in ("M", "N", "O"):
        return ReturnKind(eax=False, edx=False, st0=True)
    if ret[:1] in ("U", "V") or ret.startswith("?"):
        return ReturnKind()  # a struct by value: be conservative
    return ReturnKind(eax=True, edx=False)


def analyze_callee(
    read: Callable[[int, int], bytes | None],
    addr: int,
    memo: dict[int, CalleeInfo] | None = None,
    depth: int = 0,
) -> CalleeInfo:
    """What a call to the function at `addr` does with the caller's state: how many bytes of
    arguments its `ret N` removes, and whether some path reads `ecx`/`edx` before writing them.
    `read(addr, size)` returns code bytes, or None past the end of the image."""
    # pylint: disable=import-outside-toplevel
    from capstone import Cs, CS_ARCH_X86, CS_MODE_32  # type: ignore
    from capstone import x86_const

    memo = {} if memo is None else memo
    if addr in memo:
        return memo[addr]
    memo[addr] = CalleeInfo(pops=None)  # recursion guard
    md = Cs(CS_ARCH_X86, CS_MODE_32)
    md.detail = True
    families = {
        "ecx": {
            x86_const.X86_REG_ECX,
            x86_const.X86_REG_CX,
            x86_const.X86_REG_CL,
            x86_const.X86_REG_CH,
        },
        "edx": {
            x86_const.X86_REG_EDX,
            x86_const.X86_REG_DX,
            x86_const.X86_REG_DL,
            x86_const.X86_REG_DH,
        },
    }
    decoded: dict[int, object] = {}

    def insn_at(a: int):
        if a not in decoded:
            code = read(a, 16)
            decoded[a] = next(md.disasm(code, a, 1), None) if code else None
        return decoded[a]

    reads = {"ecx": False, "edx": False}
    pops: set[int] = set()
    seen: set[tuple[int, bool, bool]] = set()
    stack = [(addr, True, True)]  # (address, ecx not yet written, edx not yet written)
    steps = 0
    while stack:
        a, un_c, un_d = stack.pop()
        while True:
            steps += 1
            if steps > 20000 or (a, un_c, un_d) in seen:
                break
            seen.add((a, un_c, un_d))
            ins = insn_at(a)
            if ins is None:
                reads["ecx"] |= un_c
                reads["edx"] |= un_d
                break
            r_read, r_write = ins.regs_access()
            if ins.mnemonic == "call":
                inner = None
                if (
                    ins.operands
                    and ins.operands[0].type == x86_const.X86_OP_IMM
                    and depth < 3
                ):
                    inner = analyze_callee(
                        read, ins.operands[0].imm & MASK, memo, depth + 1
                    )
                reads["ecx"] |= un_c and (inner is None or inner.reads_ecx)
                reads["edx"] |= un_d and (inner is None or inner.reads_edx)
                un_c = un_d = False
            else:
                # `xor ecx, ecx` reads ecx only nominally
                zero_idiom = (
                    ins.mnemonic in ("xor", "sub")
                    and len(ins.operands) == 2
                    and ins.operands[0].type
                    == x86_const.X86_OP_REG
                    == ins.operands[1].type
                    and ins.operands[0].reg == ins.operands[1].reg
                )
                if un_c and families["ecx"] & set(r_read) and not zero_idiom:
                    reads["ecx"] = True
                if un_d and families["edx"] & set(r_read) and not zero_idiom:
                    reads["edx"] = True
                un_c = un_c and not (
                    families["ecx"] & set(r_write)
                    and _full_write(ins, x86_const, "ecx")
                )
                un_d = un_d and not (
                    families["edx"] & set(r_write)
                    and _full_write(ins, x86_const, "edx")
                )
            nxt = a + ins.size
            if ins.mnemonic == "ret":
                pops.add(ins.operands[0].imm if ins.operands else 0)
                break
            if ins.mnemonic == "jmp":
                op = ins.operands[0]
                if op.type == x86_const.X86_OP_IMM:
                    a = op.imm & MASK
                    continue
                # an indirect jump: a switch, or a tail call through a pointer
                reads["ecx"] |= un_c
                reads["edx"] |= un_d
                break
            if ins.mnemonic.startswith("j") or ins.mnemonic.startswith("loop"):
                op = ins.operands[0]
                if op.type == x86_const.X86_OP_IMM:
                    stack.append((op.imm & MASK, un_c, un_d))
            if ins.mnemonic == "int3":
                break
            a = nxt
    info = CalleeInfo(
        pops=pops.pop() if len(pops) == 1 else None,
        reads_ecx=reads["ecx"],
        reads_edx=reads["edx"],
    )
    memo[addr] = info
    return info


def _full_write(ins, x86, reg: str) -> bool:
    """Does the instruction overwrite all 32 bits of the register (rather than a part of it)?"""
    # pylint: disable=import-outside-toplevel
    from capstone import CS_AC_WRITE

    full = x86.X86_REG_ECX if reg == "ecx" else x86.X86_REG_EDX
    if ins.mnemonic == "cdq" and reg == "edx":
        return True
    if (
        ins.mnemonic in ("mul", "imul", "div", "idiv")
        and len(ins.operands) == 1
        and reg == "edx"
    ):
        return ins.operands[0].size == 4
    return any(
        op.type == x86.X86_OP_REG and op.reg == full and op.access & CS_AC_WRITE
        for op in ins.operands
    )
